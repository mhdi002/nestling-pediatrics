"""Build and refresh the knowledge workspace inventory (no hardcoded book list)."""

from __future__ import annotations

import logging
from pathlib import Path

from assistant.settings import get_settings

log = logging.getLogger(__name__)

_TEXT_SUFFIXES = {
    ".md",
    ".txt",
    ".json",
    ".yaml",
    ".yml",
    ".csv",
    ".pdf",
    ".png",
    ".jpg",
    ".jpeg",
    ".webp",
    ".gif",
    ".bmp",
}


def knowledge_root() -> Path:
    settings = get_settings()
    override = getattr(settings, "nestling_knowledge_dir", None)
    if override:
        return Path(override).resolve()
    return Path(settings.nestling_root).resolve() / "knowledge"


def walk_knowledge(root: Path | None = None) -> list[dict]:
    """Return every knowledge file as relative path / type / size (bytes)."""
    root = (root or knowledge_root()).resolve()
    if not root.is_dir():
        return []
    rows: list[dict] = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        if path.name.upper() == "INDEX.MD":
            continue
        rel = path.relative_to(root).as_posix()
        if any(part.startswith(".") for part in Path(rel).parts):
            continue
        suffix = path.suffix.lower()
        if suffix and suffix not in _TEXT_SUFFIXES and suffix not in {".pdf"}:
            # Still list unknown binary-ish files so the agent can discover them.
            pass
        try:
            size = path.stat().st_size
        except OSError:
            continue
        rows.append(
            {
                "path": rel,
                "suffix": suffix or "(none)",
                "bytes": size,
                "kind": _kind(suffix),
            }
        )
    return rows


def _kind(suffix: str) -> str:
    if suffix in {".md", ".txt"}:
        return "markdown"
    if suffix == ".pdf":
        return "pdf"
    if suffix in {".png", ".jpg", ".jpeg", ".webp", ".gif", ".bmp"}:
        return "image"
    if suffix in {".json", ".yaml", ".yml"}:
        return "data"
    return "file"


def write_index(root: Path | None = None) -> Path:
    """Write ``INDEX.md`` from a directory walk. Safe to call on every startup."""
    root = (root or knowledge_root()).resolve()
    root.mkdir(parents=True, exist_ok=True)
    rows = walk_knowledge(root)
    by_top: dict[str, list[dict]] = {}
    for row in rows:
        top = row["path"].split("/", 1)[0] if "/" in row["path"] else "(root)"
        by_top.setdefault(top, []).append(row)

    lines = [
        "# Knowledge inventory",
        "",
        "This file is generated by walking the knowledge directory.",
        "Add books, charts, or guidelines as files; they appear here on the next refresh.",
        "The agent should use `fs.list_dir`, `fs.glob`, `fs.read_file`, and `search.grep`",
        "to find answers — never invent clinical numbers.",
        "",
        f"Total files: {len(rows)}",
        "",
    ]
    for top in sorted(by_top):
        lines.append(f"## {top}/")
        lines.append("")
        lines.append("| path | kind | bytes |")
        lines.append("| --- | --- | ---: |")
        for row in by_top[top]:
            lines.append(f"| `{row['path']}` | {row['kind']} | {row['bytes']} |")
        lines.append("")

    index = root / "INDEX.md"
    index.write_text("\n".join(lines), encoding="utf-8")
    log.info("Wrote knowledge index with %d files at %s", len(rows), index)
    return index
